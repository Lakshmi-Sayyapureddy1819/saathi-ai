"""Generate and FREEZE the calibration responses that annotators will label (live LLM calls).

    python -m evaluations.freeze_calibration            # refuses if already frozen
    python -m evaluations.freeze_calibration --force    # refuses once any human label exists

Run once, then hand calibration_responses.json to two independent annotators. `run_evals` only reads it.
"""
import argparse
import json
import os
import sys

sys.path.append(".")
os.environ.setdefault("TRACE_FILE", "logs/eval_traces.jsonl")

from evaluations.calibration import (CalibrationIntegrityError, FrozenResponse, freeze, labels_exist,
                                     RESPONSES_FILE)
from app.workflow.graph import WorkflowGraph, execute_turn, PROMPT_VERSION
from app.workflow.state import MemberProfile, UserSessionState


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--force", action="store_true", help="replace an existing frozen set (only if no labels exist)")
    args = ap.parse_args()
    if RESPONSES_FILE.exists() and (not args.force or labels_exist()):
        print(f"{RESPONSES_FILE} already exists. " + (
            "Human labels are present, so it cannot be replaced." if labels_exist()
            else "Pass --force to replace it (no labels exist yet)."))
        return 1
    with open("evaluations/datasets/calibration_cases.json", encoding="utf-8") as f:
        cases = json.load(f)
    graph = WorkflowGraph()
    out = []
    for c in cases:
        s = UserSessionState(channel="eval", active_node="start",
                             member=MemberProfile(member_id=f"CAL_{c['case_id']}", name="Cal User", age=30))
        resp, _ = execute_turn(c["user_input"], s, graph=graph)
        if resp.startswith("[MOCK"):
            print("No real LLM is configured (mock responses). Set GEMINI_API_KEY and retry; nothing was written.")
            return 2
        out.append(FrozenResponse(case_id=c["case_id"], user_input=c["user_input"],
                                  expected_outcome=c["expected_outcome"], response=resp))
        print(f"  generated {c['case_id']}")
    try:
        fs = freeze(out, models=[graph.model_client.config["routing"]["nodes"][0]["default_model"]],
                    prompt_version=PROMPT_VERSION, note="generated by freeze_calibration", force=args.force)
    except CalibrationIntegrityError as e:
        print(f"REFUSED: {e}")
        return 1
    print(f"Frozen {len(fs.responses)} responses (sha256 {fs.meta.sha256[:12]}...). File is now read-only.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
